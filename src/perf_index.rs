//! Generator for `docs/PERF_INDEX.md`, the discovery index of records, artifacts, sources, studies and issues.
//!
//! Every cell is copied from a file in the repository (or, for a date the file does not
//! carry, from `git log` of that file). Nothing is summarized, ranked or judged, and the
//! output is sorted so that regenerating it on an unchanged tree gives the same bytes.

use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Where the index is written, relative to the repository root.
pub const INDEX_PATH: &str = "docs/PERF_INDEX.md";

const COMMIT_FIELDS: [&str; 4] = [
    "source.commit",
    "benchmarks_git_sha",
    "benchmark_commit",
    "commit",
];
const DATE_FIELDS: [&str; 4] = ["timestamp_utc", "timestamp", "created_utc", "date"];
const WORKLOAD_FIELDS: [&str; 2] = ["workload.name", "run_id"];
const SCHEMA_FIELDS: [&str; 2] = ["schema", "schema_version"];

/// Build the full index text for the repository at `root`.
pub fn generate(root: &Path) -> String {
    let mut out = String::new();
    out.push_str("# Performance discovery index (generated, not an authority)\n\n");
    out.push_str(
        "Generated by `cargo run --release --bin bench_index` from the files in this repository; \
do not edit by hand. Every status, commit and date is copied from the file named in its row \
(the field it came from is in brackets), so this page is only as true as those files. \
Architecture and plans live in aien-spark/aien-architecture. Records are validated by \
`cargo run --release --bin bench_verify_records` (see README, \"Evidence integrity\").\n\n",
    );

    out.push_str("## Records and artifacts\n\n");
    out.push_str("Scanned: `records/`, `artifacts/`, `data/`, `prime-drag-race/results/`.\n\n");
    out.push_str("| Path | Kind | Schema | Status | Workload | Commit | Date |\n");
    out.push_str("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n");
    let mut rows = Vec::new();
    for (dir, kind) in [
        ("records", "record"),
        ("artifacts", "artifact"),
        ("data", "dataset"),
        ("prime-drag-race/results", "summary"),
    ] {
        rows.extend(evidence_rows(root, dir, kind));
    }
    rows.sort();
    if rows.is_empty() {
        out.push_str("| (none) | | | | | | |\n");
    }
    for r in rows {
        out.push_str(&r);
    }

    out.push_str("\n## Active source paths\n\n");
    out.push_str("Scanned: `src/**/*.rs`, `prime-drag-race/src/**/*.rs`. The text is the first `//!` line, else the first `///` line.\n\n");
    out.push_str("| Path | First doc line |\n| :--- | :--- |\n");
    let mut sources = Vec::new();
    for dir in ["src", "prime-drag-race/src"] {
        files_with_ext(&root.join(dir), "rs", &mut sources);
    }
    sources.sort();
    for p in &sources {
        let text = fs::read_to_string(p).unwrap_or_default();
        out.push_str(&format!(
            "| `{}` | {} |\n",
            rel(root, p),
            cell(&first_doc_line(&text))
        ));
    }

    out.push_str("\n## Performance studies\n\n");
    out.push_str("Scanned: `docs/*.md` (except this file), `prime-drag-race/*.md`. The text is the first `# ` line.\n\n");
    out.push_str("| Path | Title |\n| :--- | :--- |\n");
    let studies = study_files(root);
    for p in &studies {
        let text = fs::read_to_string(p).unwrap_or_default();
        let title = text
            .lines()
            .find_map(|l| l.strip_prefix("# "))
            .unwrap_or("(no title line)")
            .trim()
            .to_string();
        out.push_str(&format!("| `{}` | {} |\n", rel(root, p), cell(&title)));
    }

    out.push_str("\n## Owning issues\n\n");
    out.push_str("Issue references (`aien-spark/<repo>#N`, `aien-dev/<repo>#N`, GitHub issue or pull links, and `## Owning issue` sections) found in the studies and records above.\n\n");
    out.push_str("| Issue | Mentioned in |\n| :--- | :--- |\n");
    let mut issues: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut scanned = studies.clone();
    files_with_ext(&root.join("records"), "json", &mut scanned);
    scanned.sort();
    for p in &scanned {
        let text = fs::read_to_string(p).unwrap_or_default();
        for issue in issue_refs(&text) {
            issues.entry(issue).or_default().insert(rel(root, p));
        }
    }
    if issues.is_empty() {
        out.push_str("| (none) | |\n");
    }
    for (issue, paths) in &issues {
        let list: Vec<String> = paths.iter().map(|p| format!("`{p}`")).collect();
        out.push_str(&format!("| {} | {} |\n", cell(issue), list.join(", ")));
    }
    out
}

/// One table row per JSON file, except that a SHA256SUMS bundle directory is one row.
fn evidence_rows(root: &Path, dir: &str, kind: &str) -> Vec<String> {
    let base = root.join(dir);
    let mut json = Vec::new();
    files_with_ext(&base, "json", &mut json);
    let mut sums = Vec::new();
    files_with_name(&base, "SHA256SUMS", &mut sums);
    let bundles: BTreeSet<PathBuf> = sums
        .iter()
        .filter_map(|p| p.parent().map(Path::to_path_buf))
        .collect();
    let mut rows = Vec::new();
    for b in &bundles {
        let listed = fs::read_to_string(b.join("SHA256SUMS"))
            .map(|t| t.lines().filter(|l| !l.trim().is_empty()).count())
            .unwrap_or(0);
        let mut members: Vec<&PathBuf> = json.iter().filter(|p| p.parent() == Some(b)).collect();
        // manifest.json first: it carries the run identity in the existing bundles.
        members.sort_by_key(|p| (p.file_name().is_none_or(|n| n != "manifest.json"), *p));
        let docs: Vec<Value> = members
            .iter()
            .filter_map(|p| serde_json::from_str(&fs::read_to_string(p).ok()?).ok())
            .collect();
        let pick = |fields: &[&str]| docs.iter().find_map(|d| first_field(d, fields));
        let date = pick(&DATE_FIELDS).unwrap_or_else(|| git_date(root, &b.join("SHA256SUMS")));
        rows.push(row(
            &format!("{}/", rel(root, b)),
            &format!("{kind} bundle ({listed} files in SHA256SUMS)"),
            pick(&SCHEMA_FIELDS),
            pick(&["status"]),
            pick(&WORKLOAD_FIELDS),
            pick(&COMMIT_FIELDS).map(|c| mark_commit(&c)),
            date,
        ));
    }
    for p in json
        .iter()
        .filter(|p| p.parent().is_none_or(|d| !bundles.contains(d)))
    {
        let doc: Option<Value> = fs::read_to_string(p)
            .ok()
            .and_then(|t| serde_json::from_str(&t).ok());
        let f = |fields: &[&str]| doc.as_ref().and_then(|d| first_field(d, fields));
        let date = f(&DATE_FIELDS).unwrap_or_else(|| git_date(root, p));
        let kind = if doc.is_none() {
            format!("{kind} (not valid JSON)")
        } else {
            kind.to_string()
        };
        rows.push(row(
            &rel(root, p),
            &kind,
            f(&SCHEMA_FIELDS),
            f(&["status"]),
            f(&WORKLOAD_FIELDS),
            f(&COMMIT_FIELDS).map(|c| mark_commit(&c)),
            date,
        ));
    }
    rows
}

fn row(
    path: &str,
    kind: &str,
    schema: Option<String>,
    status: Option<String>,
    workload: Option<String>,
    commit: Option<String>,
    date: String,
) -> String {
    let o = |v: Option<String>| cell(&v.unwrap_or_else(|| "-".into()));
    format!(
        "| `{path}` | {} | {} | {} | {} | {} | {} |\n",
        cell(kind),
        o(schema),
        o(status),
        o(workload),
        o(commit),
        cell(&date)
    )
}

/// First present scalar among `fields`, as `value [field]`.
fn first_field(doc: &Value, fields: &[&str]) -> Option<String> {
    fields.iter().find_map(|f| {
        let v = f.split('.').try_fold(doc, |cur, k| cur.get(k))?;
        let s = match v {
            Value::String(s) => s.clone(),
            Value::Number(n) => n.to_string(),
            Value::Bool(b) => b.to_string(),
            _ => return None,
        };
        Some(format!("{s} [{f}]"))
    })
}

fn mark_commit(c: &str) -> String {
    let value = c.split(" [").next().unwrap_or(c);
    if crate::evidence::is_commit(value) {
        c.to_string()
    } else {
        format!("{c} (not a full commit id)")
    }
}

/// Date of the commit that first added the file, or "not committed".
fn git_date(root: &Path, file: &Path) -> String {
    let out = Command::new("git")
        .arg("-C")
        .arg(root)
        .args(["log", "--diff-filter=A", "--format=%cs", "--"])
        .arg(rel(root, file))
        .output();
    match out {
        Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout)
            .lines()
            .last()
            .map(|d| format!("{d} [git: first commit]"))
            .unwrap_or_else(|| "not committed".into()),
        _ => "no git history".into(),
    }
}

fn first_doc_line(text: &str) -> String {
    let find = |prefix: &str| {
        text.lines()
            .map(str::trim_start)
            .find_map(|l| l.strip_prefix(prefix).map(|r| r.trim().to_string()))
            .filter(|s| !s.is_empty())
    };
    find("//!")
        .or_else(|| find("///").map(|s| format!("(item doc) {s}")))
        .unwrap_or_else(|| "(no doc comment)".into())
}

fn study_files(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for dir in ["docs", "prime-drag-race"] {
        if let Ok(entries) = fs::read_dir(root.join(dir)) {
            for e in entries.filter_map(Result::ok) {
                let p = e.path();
                if p.is_file()
                    && p.extension().is_some_and(|x| x == "md")
                    && rel(root, &p) != INDEX_PATH
                {
                    out.push(p);
                }
            }
        }
    }
    out.sort();
    out
}

/// Normalized issue references found in `text`.
pub fn issue_refs(text: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for owner in ["aien-spark/", "aien-dev/"] {
        let mut rest = text;
        while let Some(i) = rest.find(owner) {
            let after = &rest[i + owner.len()..];
            let repo_len = after
                .find(|c: char| !(c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.'))
                .unwrap_or(after.len());
            let repo = after[..repo_len].trim_end_matches('.');
            let tail = &after[repo_len..];
            let number = if let Some(t) = tail.strip_prefix('#') {
                leading_digits(t)
            } else if let Some(t) = tail
                .strip_prefix("/issues/")
                .or_else(|| tail.strip_prefix("/pull/"))
            {
                leading_digits(t)
            } else {
                ""
            };
            if !repo.is_empty() && !number.is_empty() {
                out.insert(format!("{owner}{repo}#{number}"));
            }
            rest = after;
        }
    }
    // Bare #N under an "## Owning issue" heading: the repository is not named in the text.
    let mut in_owning = false;
    for line in text.lines() {
        if line.starts_with('#') {
            in_owning = line
                .trim_start_matches('#')
                .trim()
                .eq_ignore_ascii_case("owning issue");
            continue;
        }
        if !in_owning {
            continue;
        }
        let mut rest = line;
        while let Some(i) = rest.find('#') {
            let before = rest[..i].chars().last();
            let digits = leading_digits(&rest[i + 1..]);
            if !digits.is_empty()
                && before
                    .is_none_or(|c| !c.is_ascii_alphanumeric() && c != '-' && c != '_' && c != '.')
            {
                out.insert(format!("#{digits} (repository not named)"));
            }
            rest = &rest[i + 1..];
        }
    }
    out
}

fn leading_digits(s: &str) -> &str {
    let n = s.find(|c: char| !c.is_ascii_digit()).unwrap_or(s.len());
    &s[..n]
}

fn files_with_ext(dir: &Path, ext: &str, out: &mut Vec<PathBuf>) {
    walk(dir, &mut |p| {
        if p.extension().is_some_and(|x| x == ext) {
            out.push(p.to_path_buf());
        }
    });
}

fn files_with_name(dir: &Path, name: &str, out: &mut Vec<PathBuf>) {
    walk(dir, &mut |p| {
        if p.file_name().is_some_and(|n| n == name) {
            out.push(p.to_path_buf());
        }
    });
}

fn walk(dir: &Path, f: &mut dyn FnMut(&Path)) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(Result::ok).map(|e| e.path()).collect();
    paths.sort();
    for p in paths {
        if p.file_name().is_some_and(|n| n == "target" || n == ".git") {
            continue;
        }
        if p.is_dir() {
            walk(&p, f);
        } else {
            f(&p);
        }
    }
}

fn rel(root: &Path, p: &Path) -> String {
    crate::evidence::display_path(root, p)
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_issue_references() {
        let text = "See aien-spark/omega#308, https://github.com/aien-dev/benchmarks/issues/12 and aien-spark/aienos.\n\
## Owning issue\n\nTracked in #233 and aien-spark/aien-architecture#233.\n## Next\n#9 is not owned here\n";
        let got: Vec<String> = issue_refs(text).into_iter().collect();
        assert_eq!(
            got,
            vec![
                "#233 (repository not named)",
                "aien-dev/benchmarks#12",
                "aien-spark/aien-architecture#233",
                "aien-spark/omega#308",
            ]
        );
    }

    #[test]
    fn doc_line_fallbacks() {
        assert_eq!(first_doc_line("//! Module.\n/// Item."), "Module.");
        assert_eq!(first_doc_line("use x;\n/// Item."), "(item doc) Item.");
        assert_eq!(first_doc_line("fn main() {}"), "(no doc comment)");
    }
}
